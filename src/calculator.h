#ifndef CALCULATOR_H
#define CALCULATOR_H

/**
 * @brief Additionne deux entiers
 * @param a Premier nombre
 * @param b Deuxième nombre
 * @return La somme de a et b
 */
int add(int a, int b);

/**
 * @brief Soustrait deux entiers
 * @param a Premier nombre
 * @param b Deuxième nombre
 * @return La différence de a et b
 */
int subtract(int a, int b);

#endif
